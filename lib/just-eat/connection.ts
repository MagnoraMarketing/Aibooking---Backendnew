import "server-only";
import { randomBytes } from "node:crypto";
import type { z } from "zod";
import { getAdminClient } from "@/lib/database/admin";
import { encryptSecret, decryptSecret } from "@/lib/security/crypto";
import type { JetAddress } from "./api";

// An agent's Just Eat (JET Go) delivery setup lives in
// widget_settings.extra.justEat, next to Uber Direct's. The API key and the
// webhook token are stored encrypted and never leave the server: every route
// that hands `extra` to a browser goes through publicWidgetExtra()
// (lib/uber-direct/connection.ts), which summarizes this block too.

export const JUST_EAT_EXTRA_KEY = "justEat";

interface StoredJustEat {
  enabled?: boolean;
  apiKeyEncrypted?: string;
  // Generated by us, not by Just Eat: JET Go's webhook signing isn't public,
  // so the webhook URL carries a per-agent secret token instead.
  webhookTokenEncrypted?: string;
  pickup?: {
    name?: string;
    phone?: string;
    street?: string;
    postalCode?: string;
    city?: string;
    country?: string;
    notes?: string;
  };
}

export { justEatInputSchema } from "@/lib/security/schemas";
import type { justEatInputSchema } from "@/lib/security/schemas";
export type JustEatInput = z.input<typeof justEatInputSchema>;

export interface JustEatConfig {
  apiKey: string;
  pickup: JetAddress & { name: string; phone: string; notes?: string };
  webhookToken: string | null;
}

// Safe to show in a browser: which fields are set, never their secret values.
export interface JustEatSummary {
  enabled: boolean;
  hasApiKey: boolean;
  pickup: StoredJustEat["pickup"] | null;
}

function stored(extra: Record<string, unknown> | null | undefined): StoredJustEat | null {
  const value = extra?.[JUST_EAT_EXTRA_KEY];
  return value && typeof value === "object" ? (value as StoredJustEat) : null;
}

export function summarizeJustEat(extra: Record<string, unknown> | null | undefined): JustEatSummary | null {
  const s = stored(extra);
  if (!s) return null;
  return { enabled: Boolean(s.enabled), hasApiKey: Boolean(s.apiKeyEncrypted), pickup: s.pickup ?? null };
}

// Merges an input into what is stored: a new API key is encrypted, an omitted
// one keeps the stored value; the webhook token is made once and kept.
export function mergeJustEatInput(extra: Record<string, unknown>, input: JustEatInput): Record<string, unknown> {
  const current = stored(extra) ?? {};
  const next: StoredJustEat = {
    enabled: input.enabled,
    apiKeyEncrypted: input.apiKey ? encryptSecret(input.apiKey) : current.apiKeyEncrypted,
    webhookTokenEncrypted: current.webhookTokenEncrypted ?? encryptSecret(randomBytes(24).toString("hex")),
    pickup: { ...input.pickup, country: (input.pickup.country ?? "DK").toUpperCase() },
  };
  return { ...extra, [JUST_EAT_EXTRA_KEY]: next };
}

export function removeJustEat(extra: Record<string, unknown>): Record<string, unknown> {
  const { [JUST_EAT_EXTRA_KEY]: _removed, ...rest } = extra;
  return rest;
}

// The webhook URL to paste into Just Eat's partner portal, token included.
export function justEatWebhookToken(extra: Record<string, unknown> | null | undefined): string | null {
  const s = stored(extra);
  if (!s?.webhookTokenEncrypted) return null;
  try {
    return decryptSecret(s.webhookTokenEncrypted);
  } catch {
    return null;
  }
}

// The runtime view: only an enabled, complete setup counts, so an agent is
// never given delivery tools that can only fail in front of a customer.
export function resolveJustEatConfig(extra: Record<string, unknown> | null | undefined): JustEatConfig | null {
  const s = stored(extra);
  if (!s?.enabled || !s.apiKeyEncrypted) return null;
  const p = s.pickup;
  if (!p?.name || !p.phone || !p.street || !p.postalCode || !p.city) return null;

  let apiKey: string;
  try {
    apiKey = decryptSecret(s.apiKeyEncrypted);
  } catch (err) {
    console.error("Failed to decrypt Just Eat credentials:", err);
    return null;
  }

  return {
    apiKey,
    pickup: {
      name: p.name,
      phone: p.phone,
      street: p.street,
      postalCode: p.postalCode,
      city: p.city,
      country: p.country ?? "DK",
      notes: p.notes,
    },
    webhookToken: justEatWebhookToken(extra),
  };
}

export async function loadJustEatConfig(widgetId: string): Promise<JustEatConfig | null> {
  const supabase = getAdminClient();
  const { data } = await supabase.from("widget_settings").select("extra").eq("widget_id", widgetId).maybeSingle();
  return resolveJustEatConfig((data?.extra as Record<string, unknown> | null) ?? null);
}
